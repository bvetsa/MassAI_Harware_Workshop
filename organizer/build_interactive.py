"""Generate the dial/B1 demo from the existing trained payloads and shared ECG cases."""
from hashlib import sha256
import json
from pathlib import Path
from tempfile import TemporaryDirectory
import shutil
import sys

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from model_golf import decode, firmware_headers, logits


def build():
    demo = ROOT / 'wokwi' / 'interactive'
    src = demo / 'src'
    shutil.copyfile(ROOT / 'wokwi' / 'src' / 'inference.h', src / 'inference.h')
    with np.load(ROOT / 'demo_cases.npz', allow_pickle=False) as f:
        cases = {name: f[name] for name in f.files}
    blobs = {'baseline': (ROOT / 'baseline.mgf').read_bytes(),
             'compact': (ROOT / 'organizer' / 'rehearsal-int8.mgf').read_bytes()}
    report = {}
    model_headers = ['#pragma once', '#include <stdint.h>']
    with TemporaryDirectory() as temp:
        for name, blob in blobs.items():
            path = Path(temp) / name
            z = firmware_headers(blob, cases, path)
            body = '\n'.join(line for line in (path / 'model_data.h').read_text().splitlines()
                             if not line.startswith(('#pragma once', '#include')))
            model_headers.extend([f'namespace {name} {{', body, '}'])
            report[name] = dict(bytes=len(blob), sha256=sha256(blob).hexdigest(),
                                logits={str(i): float(v) for i, v in zip(cases['id'], z)})
        shutil.copyfile(Path(temp) / 'baseline' / 'demo_data.h', src / 'demo_data.h')
    compact_logits = logits(decode(blobs['compact']), cases['x'])
    with (src / 'demo_data.h').open('a') as file:
        file.write('constexpr float kCompactLogits[] = {' + ', '.join(f'{v:.8e}f' for v in compact_logits) + '};\n')
    (src / 'model_data.h').write_text('\n'.join(model_headers) + '\n')
    parts = []
    for name in ('inference.h', 'model_data.h', 'demo_data.h', 'main.cpp'):
        parts.append('\n'.join(line for line in (src / name).read_text().splitlines()
                               if not line.startswith(('#pragma once', '#include "'))))
    (demo / 'sketch.ino').write_text('// Generated by organizer/build_interactive.py\n#include <Arduino.h>\n' + '\n\n'.join(parts) + '\n')
    (demo / 'expected.json').write_text(json.dumps(report, indent=2) + '\n')
    for name in ('platformio.ini', 'wokwi.toml'):
        shutil.copyfile(ROOT / 'wokwi' / name, demo / name)
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    build()
